// Converts NCBI-format substitution matrices in vendor/matrices into a TypeScript module.
// Source files are the NCBI matrices as redistributed by Biopython (Bio/Align/substitution_matrices/data).
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = ['BLOSUM45', 'BLOSUM62', 'BLOSUM80', 'PAM250', 'NUC.4.4'];

function parse(text) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim() && !l.startsWith('#'));
  const cols = lines[0].trim().split(/\s+/);
  const rows = {};
  for (const line of lines.slice(1)) {
    const parts = line.trim().split(/\s+/);
    const key = parts[0];
    const vals = parts.slice(1).map(Number);
    if (vals.length !== cols.length) throw new Error(`row ${key}: ${vals.length} != ${cols.length}`);
    rows[key] = vals;
  }
  const alphabet = cols.join('');
  for (const c of cols) if (!rows[c]) throw new Error(`missing row ${c}`);
  const flat = [];
  for (const r of cols) flat.push(...rows[r]);
  // symmetry check
  const n = cols.length;
  for (let i = 0; i < n; i++)
    for (let j = 0; j < n; j++)
      if (flat[i * n + j] !== flat[j * n + i]) throw new Error(`asymmetric ${cols[i]}${cols[j]}`);
  return { alphabet, scores: flat };
}

let out = '// AUTO-GENERATED by scripts/gen-matrices.mjs — do not edit by hand.\n';
out += '// Source: NCBI substitution matrices (as distributed with Biopython).\n\n';
out += 'export interface RawMatrix { alphabet: string; scores: number[] }\n\n';
out += 'export const RAW_MATRICES: Record<string, RawMatrix> = {\n';
for (const name of NAMES) {
  const { alphabet, scores } = parse(readFileSync(`vendor/matrices/${name}`, 'utf8'));
  out += `  '${name}': { alphabet: '${alphabet}', scores: [${scores.join(',')}] },\n`;
}
out += '};\n';
writeFileSync('src/core/matrices.generated.ts', out);
console.log('wrote src/core/matrices.generated.ts');
